"""Controller-side final report assembly. Measured data and AI text are kept strictly separate and labelled."""
from __future__ import annotations

import json
from typing import Any, Dict, List

from app.services.orchestration.common import now_iso

REQUIRED_SECTIONS = ["## Measured telemetry", "## AI-generated summary", "## Provenance"]


def _row(label: str, value: Any) -> str:
    return f"| {label} | {value if value is not None else 'n/a'} |"


def assemble_project_report(run: Dict[str, Any], title: str, results: Dict[str, Dict[str, Any]],
                            provenance: List[Dict[str, Any]], objective: Optional[str] = None) -> Dict[str, Any]:
    """Return ``{"markdown": str, "json": dict}`` from accepted task results for any project type."""
    from typing import Optional
    telemetry = {k: v for k, v in results.items() if v.get("kind") == "worker_telemetry"}
    ai = {k: v for k, v in results.items() if v.get("kind") == "model_output"}
    other = {k: v for k, v in results.items() if v.get("kind") not in ("worker_telemetry", "model_output")}

    md: List[str] = [f"# {title}", "",
                     f"Generated by the Qwen Collective Project Orchestrator (run `{run['id']}`) at {now_iso()}.", ""]

    if objective:
        md += ["## Objective", "", str(objective).strip(), ""]

    if telemetry:
        md += ["## Measured telemetry",
               "_Values below were measured by sandboxed diagnostics on the named node and validated against "
               "schema `qc.health.v1`. They are reproduced verbatim, not produced by any model._", ""]
        for key, r in sorted(telemetry.items()):
            d = r.get("data", {})
            md += [f"### Node `{r.get('node')}`", "", "| Metric | Value |", "|---|---|",
                   _row("OS", d.get("os")), _row("Kernel", d.get("kernel")), _row("CPU count", d.get("cpu_count")),
                   _row("Load average (1/5/15 min)", d.get("loadavg")),
                   _row("Memory total / available (MiB)", f"{d.get('mem_total_mib')} / {d.get('mem_available_mib')}"),
                   _row("Swap total / free (MiB)", f"{d.get('swap_total_mib')} / {d.get('swap_free_mib')}"),
                   _row("Root disk total / free (GiB)", f"{d.get('disk_root_total_gib')} / {d.get('disk_root_free_gib')}"),
                   _row("Uptime (s)", d.get("uptime_seconds")), _row("Python", d.get("python")),
                   _row("Collected (UTC)", d.get("collected_utc")), ""]

    if ai:
        md += ["## AI-generated summary", ""]
        for key, r in sorted(ai.items()):
            md += [f"> **AI-generated, unverified.** Model `{r.get('model')}` on node `{r.get('node')}`. "
                   "This is an interpretation of the project inputs, not a measurement.", "",
                   r.get("text", ""), ""]
    elif not telemetry and not other:
        md += ["## AI-generated summary", "", "_No AI summary was requested or produced for this run._", ""]

    if other:
        md += ["## Operational Results", ""]
        for key, r in sorted(other.items()):
            md += [f"### Task `{key}`", "", f"```json\n{json.dumps(r, indent=2)}\n```", ""]

    md += ["## Provenance", "", "| Task | Node | Attempts | Kind |", "|---|---|---|---|"]
    for p in provenance:
        md.append(f"| {p['key']} | {p.get('node') or 'controller'} | {p.get('attempts')} | {p.get('kind')} |")

    report_json = {"schema": "qc.report.v1", "run_id": run["id"], "generated_utc": now_iso(),
                   "title": title,
                   "measured": {r.get("node"): r.get("data") for r in telemetry.values()},
                   "ai_summary": [{"model": r.get("model"), "node": r.get("node"), "text": r.get("text"),
                                   "label": "AI-generated, unverified"} for r in ai.values()],
                   "provenance": provenance}
    return {"markdown": "\n".join(md) + "\n", "json": report_json, "json_text": json.dumps(report_json, indent=2)}


def assemble_health_report(run: Dict[str, Any], title: str, results: Dict[str, Dict[str, Any]],
                           provenance: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Backward-compatible health report assembly."""
    return assemble_project_report(run, title, results, provenance)
